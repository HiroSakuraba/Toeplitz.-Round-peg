"""Mod-2 Floer grading of square generators (v331, second step).

Greene-Lobb's Jordan Floer complex at angle theta is generated by the transverse points of
L0 = gamma x gamma and L1 = R_theta(L0) in C^2 (away from the diagonal), and its homology is
F2 in gradings 1 and 2. For oriented Lagrangians the grading of a transverse generator x is,
modulo 2, determined by the local intersection sign eps(x) of (T_x L0, T_x L1), up to one
universal constant. This module

* computes eps(x) exactly for square generators on rational polygons (theta = pi/2, where
  R is rational: alpha = (1+i)/2, beta = (1-i)/2) and in floating point for ellipse
  rectangles at other angles;
* calibrates the universal constant on an ellipse, where by continuation to theta -> 0 the
  major-axis rectangle has grading 2 (the diameter, maximum of H) and the minor-axis
  rectangle grading 1 (a saddle of H);
* checks the Euler characteristic: the signs over all generators of a generic polygon sum to 0.

The product orientation of gamma x gamma does not depend on the direction of gamma, so eps is
intrinsic. Only the grading modulo 2 is computed; the integer grading needs the Maslov index of
the preferred capping, which is not computed here.
"""
from fractions import Fraction as Q
import cmath
import math

from angular_windows_v328_v330 import area, primitive


def _det4(m):
    """Exact determinant of a 4x4 matrix by cofactor expansion."""
    def det3(a):
        return (a[0][0]*(a[1][1]*a[2][2]-a[1][2]*a[2][1]) - a[0][1]*(a[1][0]*a[2][2]-a[1][2]*a[2][0])
                + a[0][2]*(a[1][0]*a[2][1]-a[1][1]*a[2][0]))
    total = 0
    for c in range(4):
        minor = [[m[r][k] for k in range(4) if k != c] for r in range(1, 4)]
        total += (-1)**c * m[0][c] * det3(minor)
    return total


def _rotate_pair(a, b, alpha, beta):
    """R(a, b) = (alpha a + beta b, beta a + alpha b) on complex numbers given as (x, y)."""
    mul = lambda u, v: (u[0]*v[0]-u[1]*v[1], u[0]*v[1]+u[1]*v[0])
    add = lambda u, v: (u[0]+v[0], u[1]+v[1])
    return add(mul(alpha, a), mul(beta, b)), add(mul(beta, a), mul(alpha, b))


def intersection_sign(tz, tw, sz, sw, alpha, beta):
    """Sign of det(T L0, T L1) at x = (z, w), where tz, tw are tangents at z, w and sz, sw are
    tangents at p = R^{-1} x. Each tangent is a planar vector; vectors live in C^2 = R^4."""
    zero = (0, 0)
    cols = [(tz, zero), (zero, tw), _rotate_pair(sz, zero, alpha, beta), _rotate_pair(zero, sw, alpha, beta)]
    m = [[col[0][0] for col in cols], [col[0][1] for col in cols], [col[1][0] for col in cols], [col[1][1] for col in cols]]
    d = _det4(m)
    return (d > 0) - (d < 0)


# ---------------------------------------------------------------- polygons, theta = pi/2

QUARTER = ((Q(1, 2), Q(1, 2)), (Q(1, 2), Q(-1, 2)))    # alpha = (1+i)/2, beta = (1-i)/2


def contact_edges(P, square):
    """For each vertex of a square, the unique edge containing it in its relative interior,
    or None when the contact is at a polygon vertex (tangent undefined)."""
    n = len(P)
    out = []
    for v in square:
        hit = None
        for m in range(n):
            a, b = P[m], P[(m+1) % n]
            d = (b[0]-a[0], b[1]-a[1])
            if d[0]*(v[1]-a[1])-d[1]*(v[0]-a[0]) == 0 and 0 < (v[0]-a[0])*d[0]+(v[1]-a[1])*d[1] < d[0]**2+d[1]**2:
                hit = m
                break
        out.append(hit)
    return out


def square_generators(P, square, edges=None, F=None, A=None):
    """The two inequivalent generators of a counterclockwise square (c0,c1,c2,c3) at theta = pi/2.

    x = (c1, c3) = R(c0, c2) has action residue r = -[(F0-F1)+(F2-F3)] mod A; the other,
    x' = (c2, c0) = R(c1, c3), has residue A - r. (Each also has a swapped twin (w, z) with the
    same sign and action.) Returns [(residue, sign), (residue', sign')], sign None at vertex contacts."""
    n = len(P)
    edges = edges if edges is not None else contact_edges(P, square)
    F = F or primitive(P+[P[0]])
    A = A or area(P)
    if any(e is None for e in edges):
        signs = (None, None)
    else:
        t = [(P[(e+1) % n][0]-P[e][0], P[(e+1) % n][1]-P[e][1]) for e in edges]
        alpha, beta = QUARTER
        signs = (intersection_sign(t[1], t[3], t[0], t[2], alpha, beta),
                 intersection_sign(t[2], t[0], t[1], t[3], alpha, beta))
    Fv = []
    for v, e in zip(square, edges):
        m = e
        if m is None:   # vertex contact: the primitive is continuous, use any edge through the point
            m = next(k for k in range(n) if P[k] == v)
        Fv.append(F[m]+(P[m][0]*v[1]-P[m][1]*v[0])/2)
    r = (-((Fv[0]-Fv[1])+(Fv[2]-Fv[3]))) % A
    return [(r, signs[0]), ((A-r) % A, signs[1])]


# ---------------------------------------------------------------- ellipse calibration

def ellipse_rectangle_signs(a, b, theta):
    """Intersection signs of the two rectangle generators of the ellipse at angle theta.

    Returns (major_branch_sign, minor_branch_sign). The major-axis branch has diagonals at
    angles +-theta/2 from the x-axis; the minor-axis branch at pi/2 +- theta/2."""
    e = cmath.exp(1j*theta)
    alpha, beta = ((1+e)/2), ((1-e)/2)
    alpha, beta = (alpha.real, alpha.imag), (beta.real, beta.imag)

    def point_tangent(psi):
        phi = math.atan2(a*math.sin(psi), b*math.cos(psi))   # ellipse parameter with polar angle psi
        return (a*math.cos(phi), b*math.sin(phi)), (-a*math.sin(phi), b*math.cos(phi))

    out = []
    for base in (0.0, math.pi/2):
        d0, d1 = base-theta/2, base+theta/2          # the first diagonal rotates by theta onto the second
        (z0, tz0), (z1, tz1) = point_tangent(d0), point_tangent(d1)
        (w0, tw0), (w1, tw1) = point_tangent(d0+math.pi), point_tangent(d1+math.pi)
        # generator x = (z1, w1) = R_theta(z0, w0)
        out.append(intersection_sign(tz1, tw1, tz0, tw0, alpha, beta))
    return tuple(out)


def calibration(a=2.0, b=1.0, thetas=(0.3, 0.7, 1.0, 1.3)):
    """The sign carried by grading 2 (constant over the calibration angles), or an error."""
    pairs = {ellipse_rectangle_signs(a, b, t) for t in thetas}
    if len(pairs) != 1:
        raise ArithmeticError("calibration sign varies with the angle", pairs)
    major, minor = pairs.pop()
    if major == minor or 0 in (major, minor):
        raise ArithmeticError("ellipse branches do not have opposite signs")
    return major


def euler_characteristic(P, squares):
    """Sum of signs over all generators of all squares (each generator twice: (z,w) and (w,z))."""
    total, undefined = 0, 0
    for sq in squares:
        gens = square_generators(P, sq)
        if any(s is None for _, s in gens):
            undefined += 1
            continue
        total += 2*sum(s for _, s in gens)
    return total, undefined


# ---------------------------------------------------------------- survivor filter and report

def parity_filter(N, workers=4):
    """Apply the mod-2 grading to the v331 residue survivors of the N-turn fixture.

    For each surviving square exactly one of its two generators has action residue in the
    spectral window [A/2, pi R^2/2]; it can carry the grading-2 class only if its sign is the
    calibrated grading-2 sign."""
    from residue_census_v331 import census, midside_fixture
    from angular_windows_v328_v330 import pi_enclosure, radius_squared
    even = calibration()
    row = census(N, workers=workers)
    P = midside_fixture(N)
    A, F = area(P), primitive(P+[P[0]])
    top = pi_enclosure(30)[1]*radius_squared(P)/2
    tally = {"survivors": len(row["survivors"]), "even": 0, "odd": 0, "vertex_contact": 0, "ambiguous_window": 0}
    for _, sq in row["survivors"]:
        window = [(r, s) for r, s in square_generators(P, sq, F=F, A=A) if A/2 <= r <= top]
        if len(window) != 1:
            tally["ambiguous_window"] += 1
        elif window[0][1] is None:
            tally["vertex_contact"] += 1
        else:
            tally["even" if window[0][1] == even else "odd"] += 1
    return {"N": N, **tally}


def report(large=False):
    from fractions import Fraction as Fr
    polygons = {
        "irregular 12-gon": [(0, 0), (5, 1), (9, 0), (11, 4), (8, 5), (10, 9), (6, 8), (4, 11), (2, 7), (-2, 9), (-1, 4), (-3, 2)],
        "convex pentagon": [(0, 0), (7, 1), (8, 6), (3, 9), (-2, 5)],
    }
    from residue_census_v331 import certify, float_search
    checks = []
    for name, poly in polygons.items():
        P = [(Fr(x), Fr(y)) for x, y in poly]
        quads, *_ = float_search(P, qmax2=1e9)
        found, _ = certify(P, quads, qmax2=Fr(10**9))
        total, undefined = euler_characteristic(P, [v[0] for v in found.values()])
        checks.append({"polygon": name, "squares": len(found), "sign_sum": total, "vertex_contacts": undefined})
    return {"grading_two_sign": calibration(),
            "ellipse_signs_major_minor": {str(t): list(ellipse_rectangle_signs(2.0, 1.0, t)) for t in (0.3, 0.7, 1.0, 1.3)},
            "euler_characteristic_checks": checks,
            "survivor_parity": [parity_filter(N) for N in ((30,) if large else (20, 24))]}


if __name__ == "__main__":
    import json
    import sys
    print(json.dumps(report(large=sys.argv[1:] == ["--large"]), indent=2))
